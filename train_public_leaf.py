"""Fit a planning value on complete Pesten game outcomes and sampled decision states."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import random
import time

import numpy as np
import torch
from torch import nn

from batched_pesten import BatchedPesten, PHASE_CARD, PHASE_SUIT, POLICY_RANDOM, POLICY_RL
from temporal_batched_speed import SafeEventCursor, TemporalSeatRuntime, _batch_temporal_actions, build_safe_decision
from train_outcome_residual import teacher


@torch.inference_mode()
def collect_games(policy, *, players, games, seed, keep_probability):
    rng = np.random.default_rng(seed + 7_000_000)
    deals = np.arange(seed, seed + games, dtype=np.uint32)
    episode_dtype = np.min_scalar_type(games - 1)
    focal = np.arange(games) % players
    random_others = np.arange(games) // players % 2 == 0
    order = (np.arange(players)[None, :] + focal[:, None]) % players
    kinds = np.where(random_others[:, None] & (np.arange(players)[None, :] != focal[:, None]),
                     POLICY_RANDOM, POLICY_RL).astype(np.int8)
    engine = BatchedPesten(kinds, np.full(kinds.shape, "leaf", dtype=object), deals,
                           max_turns=1000, record_public_events=True)
    suit_rng = [random.Random(int(s)) for s in deals]
    seats = {(g, s): TemporalSeatRuntime(g, g, s, policy, torch.Generator(),
                                         policy.initial_state(), SafeEventCursor())
             for g in range(games) for s in range(players) if kinds[g, s] == POLICY_RL}
    records = {key: [] for key in ("hands", "sizes", "seat", "direction", "suit", "rank", "penalty", "episode")}
    while len(active := engine.active_games()):
        rows = active[(engine.phase[active] == PHASE_CARD) & (rng.random(len(active)) < keep_probability)]
        if len(rows):
            # Omniscient examples train the search value; the decision-time caller
            # supplies only hands it generated by sampling its own possible world.
            records["hands"].append(engine.hands[rows[:, None], order[rows]].astype(np.int8))
            records["sizes"].append(engine.hand_sizes[rows[:, None], order[rows]].copy())
            records["seat"].append(((engine.current_player[rows] - focal[rows]) % players).astype(np.int8))
            records["direction"].append(engine.direction[rows].copy())
            records["suit"].append(engine.current_sort[rows].copy())
            records["rank"].append(engine.current_rank[rows].copy())
            records["penalty"].append(engine.penalty_amount[rows].copy())
            records["episode"].append(rows.astype(episode_dtype))
        entries, indices = [], []
        actions = np.empty(len(active), np.int64)
        for i, row in enumerate(active):
            seat = int(engine.current_player[row])
            if kinds[row, seat] == POLICY_RANDOM:
                actions[i] = (50 + suit_rng[row].randint(0, 3) if engine.phase[row] == PHASE_SUIT
                              else engine.random_action(row))
            else:
                runtime = seats[int(row), seat]
                entries.append((runtime, build_safe_decision(engine, row, seat, runtime.cursor)))
                indices.append(i)
        if entries:
            actions[indices] = _batch_temporal_actions(policy, entries, None, deterministic=True)
            for runtime, _ in entries:
                runtime.trajectory.clear()
                runtime.safe_history.clear()
        for row, action in zip(active, actions):
            engine.apply_action(int(row), int(action))
    result = {name: np.concatenate(v) for name, v in records.items()}
    result["winners"] = np.where(engine.winners < 0, -1, (engine.winners - focal) % players).astype(np.int8)
    result["random_others"] = random_others
    result["deals"] = deals
    return result


def collect(args):
    if args.games < 1 or args.chunks < 1 or args.start < 0 or not 0 < args.keep <= 1:
        raise ValueError("use positive game and chunk counts, a nonnegative shard start, and a sampling rate in (0, 1]")
    policy = teacher(orbit_size=args.orbit, trace_cpu=not args.eager_actor)
    args.data.mkdir(parents=True, exist_ok=True)
    for i in range(args.start, args.start + args.chunks):
        dest = args.data / f"shard_{i:04}.npz"
        if dest.exists():
            raise ValueError(f"shard exists: {dest}")
        started = time.monotonic()
        data = collect_games(policy, players=2 + i % 3, games=args.games, seed=args.seed + args.games * i,
                             keep_probability=args.keep)
        with dest.open("xb") as handle:
            np.savez_compressed(handle, **data, orbit=args.orbit)
        print(json.dumps({"index": i, "states": len(data["hands"]), "seed": int(data["deals"][0]),
                          "players": data["sizes"].shape[1], "games": args.games, "seconds": time.monotonic()-started}),
              flush=True)


class LeafNet(nn.Module):
    def __init__(self, features, hidden):
        super().__init__()
        self.linear = nn.Linear(features, 1, bias=False)
        self.hidden = nn.Linear(features, hidden)
        self.out = nn.Linear(hidden, 1)
        self.draw = nn.Parameter(torch.tensor(-4.5))

    def forward(self, features, active):
        score = (self.linear(features) + self.out(self.hidden(features).relu())).squeeze(-1)
        return torch.cat((score.masked_fill(~active, -1e9), self.draw.expand(len(features), 1)), dim=1)

    def pack(self):
        return torch.cat((self.linear.weight.flatten(), self.hidden.weight.T.flatten(),
                          self.hidden.bias, self.out.weight.flatten(), self.out.bias, self.draw.reshape(1))
                         ).detach().cpu().numpy().astype(np.float64)


def load_training_data(paths):
    from public_lookahead_leaf import batch_features
    features, winners, masks, validation = [], [], [], []
    records = []
    for i, path in enumerate(paths):
        with np.load(path) as d:
            ep = d["episode"].astype(int)
            target = d["winners"][ep]
            n = d["sizes"].shape[1]
            f = batch_features(d["hands"], d["sizes"], d["seat"].astype(np.int64),
                               d["direction"].astype(np.int64), d["suit"].astype(np.int64),
                               d["rank"].astype(np.int64), d["penalty"].astype(np.int64),
                               d["random_others"][ep])
            features.append(f)
            masks.append(np.broadcast_to(np.arange(4) < n, (len(f), 4)))
            winners.append(np.where(target >= 0, target, 4))
            validation.append(np.full(len(f), i % 18 < 3))
            records.append({"file": path.name, "hash": hashlib.sha256(path.read_bytes()).hexdigest(),
                            "games": len(d["winners"]), "rows": len(ep), "players": n, "orbit": int(d["orbit"]),
                            "seed_start": int(d["deals"][0]), "seed_end": int(d["deals"][-1])+1})
    return tuple(torch.from_numpy(np.concatenate(parts)) for parts in (features, masks, winners, validation)), records


def fit(args):
    from public_lookahead_leaf import FEATURES, HIDDEN, WEIGHT_COUNT
    import copy
    paths = [args.data / f"shard_{i:04}.npz" for i in range(args.chunks)]
    if min(args.epochs, args.chunks, args.batch_size) <= 0:
        raise ValueError("epochs, shards and minibatch size must be positive")
    args.out.mkdir(parents=True, exist_ok=False)
    torch.manual_seed(args.seed)
    (f, mask, y, valid), shards = load_training_data(paths)
    f, mask, y, valid = f.to(args.device), mask.to(args.device), y.long().to(args.device), valid.to(args.device)
    train = torch.where(~valid)[0]
    tests = torch.where(valid)[0]
    if not len(train) or not len(tests):
        raise ValueError("shards need to contain both training and validation games")
    model = LeafNet(FEATURES, HIDDEN).to(args.device)
    optim = torch.optim.AdamW(model.parameters(), lr=.004)
    lr = torch.optim.lr_scheduler.CosineAnnealingLR(optim, args.epochs, eta_min=.0005)
    history = []
    best = None
    best_loss = float("inf")
    for epoch in range(args.epochs):
        order = train[torch.randperm(len(train), device=args.device)]
        for ids in order.split(args.batch_size):
            logits = model(f[ids], mask[ids])
            loss = nn.functional.cross_entropy(logits, y[ids])
            optim.zero_grad()
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 5.)
            optim.step()
        lr.step()
        with torch.inference_mode():
            logits = model(f[tests], mask[tests])
            nll = float(nn.functional.cross_entropy(logits, y[tests]))
            mse = float((logits.softmax(1)[:, 0] - (y[tests] == 0).float()).square().mean())
        history.append({"epoch": epoch+1, "validation_nll": nll, "validation_focal_brier": mse})
        if nll < best_loss:
            best_loss = nll
            best = copy.deepcopy(model.state_dict())
        if epoch == 0 or (epoch+1)%5 == 0:
            print(json.dumps(history[-1]), flush=True)
    model.load_state_dict(best)
    weights = model.pack()
    assert len(weights) == WEIGHT_COUNT
    path = args.out / "leaf_weights.npy"
    np.save(path, weights, allow_pickle=False)
    with torch.inference_mode():
        features = f[tests]
        # The first feature caps very large hands, whereas the log-size feature
        # retains the true size for the previous hand-size heuristic.
        sizes = torch.expm1(features[:, :, 1] * 2).round()
        heuristic = (-.4*(sizes + 2.5*features[:,:,7] - .6*features[:,:,31])).masked_fill(~mask[tests],-1e9)
        # The existing leaf normalizes seat scores without a draw class. Its focal
        # Brier score uses that exact probability. Compare log loss on decisive games.
        decisive = y[tests] != 4
        heuristic_nll = float(nn.functional.cross_entropy(heuristic[decisive], y[tests][decisive]))
        heuristic_brier = float((heuristic.softmax(1)[:,0] - (y[tests]==0).float()).square().mean())
        learned = model(f[tests], mask[tests])
        learned_decisive_nll = float(nn.functional.cross_entropy(learned[decisive,:4], y[tests][decisive]))
    report = {"seed": args.seed, "games": sum(s["games"] for s in shards), "rows": len(f),
              "training_rows": len(train), "validation_rows": len(tests), "training_orbits": sorted({s["orbit"] for s in shards}),
              "validation_split": "entire first three shards of each consecutive eighteen",
              "history": history, "heuristic_decisive_nll": heuristic_nll, "learned_decisive_nll": learned_decisive_nll, "heuristic_validation_focal_brier": heuristic_brier,
              "best_epoch": min(history, key=lambda row:row["validation_nll"]),
              "weights_sha256": hashlib.sha256(path.read_bytes()).hexdigest(), "shards": shards}
    (args.out/"fit.json").write_text(json.dumps(report,indent=2)+"\n")
    print(json.dumps({k:report[k] for k in ("games","rows","best_epoch","heuristic_decisive_nll","learned_decisive_nll","weights_sha256")}),flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parsers = parser.add_subparsers(dest="operation", required=True)
    cmd = parsers.add_parser("collect")
    cmd.add_argument("--data", type=Path, required=True)
    cmd.add_argument("--chunks", type=int, default=36)
    cmd.add_argument("--start", type=int, default=0)
    cmd.add_argument("--games", type=int, default=384)
    cmd.add_argument("--seed", type=int, default=1_111_000_000)
    cmd.add_argument("--keep", type=float, default=.18)
    cmd.add_argument("--orbit", type=int, choices=(1, 4, 24), default=1)
    cmd.add_argument("--eager-actor", action="store_true",
                     help="use the original eager CPU collector for archived trajectory reproduction")
    cmd.set_defaults(func=collect)
    trainer = parsers.add_parser("fit")
    trainer.add_argument("--data", type=Path, required=True)
    trainer.add_argument("--out", type=Path, required=True)
    trainer.add_argument("--chunks", type=int, default=60)
    trainer.add_argument("--epochs", type=int, default=22)
    trainer.add_argument("--batch-size", type=int, default=2048)
    trainer.add_argument("--device", default="cuda", choices=("cpu", "cuda"))
    trainer.add_argument("--seed", type=int, default=1_111_111_707)
    trainer.set_defaults(func=fit)
    args = parser.parse_args()
    torch.set_num_threads(1)
    args.func(args)


if __name__ == "__main__":
    main()
